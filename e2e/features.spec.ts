import { test, expect } from '@playwright/test'
import { onboard, addMember, readStore } from './helpers'

test.describe('member profile, workout plans and activity', () => {
  test('member profile fields (height, weight), member code and check-in by code', async ({ page }) => {
    await onboard(page, 'empty')
    await page.goto('/members/new')
    await page.getByLabel('Full name').fill('Priya Code')
    await page.getByLabel(/^Phone/).fill('98200 00031')
    await page.getByLabel('Date of birth').fill('1990-05-20')
    await page.getByLabel('Gender').selectOption('female')
    // Fields that were removed from the form stay gone.
    for (const label of ['Email', 'Trainer', 'Emergency contact', 'Emergency phone']) await expect(page.getByLabel(label, { exact: true })).toHaveCount(0)
    // Bad measurements are refused with a message and nothing is saved.
    await page.getByLabel('Height (cm)').fill("5'8")
    await page.getByLabel('Weight (kg)').fill('700')
    await page.getByRole('button', { name: 'Add member' }).click()
    await expect(page.getByText('Enter a number in cm, like 172')).toBeVisible()
    await expect(page.getByText('Enter between 20 and 300 kg')).toBeVisible()
    expect((await readStore(page, 'members')).length).toBe(0)
    await page.getByLabel('Height (cm)').fill('172')
    await page.getByLabel('Weight (kg)').fill('68.5')
    await page.getByLabel('Fitness goal').fill('Strength')
    await page.getByLabel('Health notes').fill('Asthma; keep inhaler nearby')
    await page.getByRole('button', { name: 'Add member' }).click()
    await expect(page).toHaveURL(/\/members\/mem_/)
    const main = page.getByRole('main')
    await expect(main).toContainText('GB-0001')
    await expect(main).toContainText('172 cm')
    await expect(main).toContainText('68.5 kg')
    for (const label of ['Email', 'Trainer', 'Emergency contact']) await expect(main.getByText(label, { exact: true })).toHaveCount(0)
    await expect(page.getByRole('tab', { name: /PT sessions/ })).toHaveCount(0)
    await expect(main).toContainText('Asthma; keep inhaler nearby')
    await expect(main).toContainText('Strength')
    const stored = await readStore<{ memberCode: string; dateOfBirth: string; gender: string; heightCm: number; weightKg: number }>(page, 'members')
    expect(stored[0]).toMatchObject({ memberCode: 'GB-0001', dateOfBirth: '1990-05-20', gender: 'female', heightCm: 172, weightKg: 68.5 })
    for (const k of ['email', 'trainerId', 'emergencyName', 'emergencyPhone']) expect(k in stored[0]).toBe(false)

    // Editing shows the saved values and clearing one removes it.
    await page.getByRole('link', { name: 'Edit' }).click()
    await expect(page.getByLabel('Height (cm)')).toHaveValue('172')
    await expect(page.getByLabel('Weight (kg)')).toHaveValue('68.5')
    await page.getByLabel('Weight (kg)').fill('')
    await page.getByLabel('Height (cm)').fill('173')
    await page.getByRole('button', { name: 'Save changes' }).click()
    await expect(page).toHaveURL(/\/members\/mem_[^/]+$/)
    await expect(main).toContainText('173 cm')
    const edited = (await readStore<{ heightCm?: number; weightKg?: number }>(page, 'members'))[0]
    expect(edited.heightCm).toBe(173)
    expect(edited.weightKg).toBeUndefined()

    await page.goto('/attendance')
    await page.getByRole('combobox').fill('GB-0001')
    await expect(page.getByRole('option', { name: /Priya Code/ })).toBeVisible()
  })

  test('removed sections: no navigation entry and their addresses show the not-found page', async ({ page }) => {
    await onboard(page, 'sample')
    const nav = page.getByRole('navigation', { name: 'Main' })
    for (const label of ['PT sessions', 'Trainers', 'Equipment', 'Expenses']) await expect(nav.getByRole('link', { name: label, exact: true })).toHaveCount(0)
    for (const label of ['Dashboard', 'Members', 'Attendance', 'Payments', 'Follow-ups', 'Plans', 'Workout plans', 'Reports', 'Activity', 'Settings']) await expect(nav.getByRole('link', { name: label, exact: true })).toBeVisible()
    const main = page.getByRole('main')
    await expect(main).not.toContainText(/PT session|Equipment|Expenses|Net cash/)
    await page.goto('/reports')
    await expect(page.getByRole('main')).toContainText('Revenue received')
    await expect(page.getByRole('main')).not.toContainText(/Expenses|Net cash/)
    await expect(page.getByRole('button', { name: 'Expenses' })).toHaveCount(0)
    for (const route of ['/trainers', '/sessions', '/equipment', '/expenses']) {
      await page.goto(route)
      await expect(page.getByRole('heading', { name: 'This page doesn’t exist' }), route).toBeVisible()
      await expect(page, route).toHaveTitle(/Page not found/)
    }
    for (const store of ['trainers', 'schedules', 'sessions', 'equipment', 'incidents', 'expenses']) expect((await readStore(page, store)).length, store).toBe(0)
  })

  test('workout plans: use a template, assign to a member, print sheet shows member', async ({ page, context }) => {
    await onboard(page, 'empty')
    const memberUrl = await addMember(page, 'Plan Pat', '98200 00051')
    await page.goto('/workouts')
    await page.getByRole('button', { name: 'Use template' }).first().click()
    await expect(page.getByRole('status').filter({ hasText: 'Added' })).toBeVisible()
    expect((await readStore<{ source: string }>(page, 'workouts'))[0].source).toBe('library')
    await page.goto(memberUrl)
    const select = page.getByLabel('Assign workout plan')
    await select.selectOption({ index: 1 })
    await expect.poll(async () => (await readStore<{ workoutPlanId?: string }>(page, 'members'))[0].workoutPlanId).toBeTruthy()
    await expect(select.locator('option:checked')).toHaveText(/Beginner full body/)
    const [sheet] = await Promise.all([context.waitForEvent('page'), page.getByRole('button', { name: 'Print sheet' }).click()])
    await sheet.waitForLoadState()
    await expect(sheet.getByRole('article')).toContainText('Prepared for')
    await expect(sheet.getByRole('article')).toContainText('Plan Pat')
    await expect(sheet.getByRole('article')).toContainText('Beginner full body')
    await sheet.close()
  })

  test('activity page lists and filters events; new pages have no overflow at 390px', async ({ page }) => {
    await onboard(page, 'sample')
    await page.goto('/activity')
    await expect(page.getByRole('main')).toContainText('Loaded labelled sample data')
    await expect(page.getByLabel('Kind').locator('option')).toHaveText(['All kinds', 'Members', 'Memberships', 'Payments', 'Invoices', 'Attendance', 'Workouts', 'Follow-ups', 'System'])
    await page.getByLabel('Kind').selectOption('system')
    await expect(page.getByRole('main')).toContainText('System')
    await page.setViewportSize({ width: 390, height: 844 })
    for (const route of ['/workouts', '/activity', '/reports', '/']) {
      await page.goto(route)
      await page.waitForLoadState('networkidle')
      const { scrollW, inner } = await page.evaluate(() => ({ scrollW: document.documentElement.scrollWidth, inner: window.innerWidth }))
      expect(scrollW, route).toBeLessThanOrEqual(inner)
    }
  })
})
