import { test, expect } from '@playwright/test'
import { onboard, addMember, readStore } from './helpers'

test.describe('training and operations features', () => {
  test('member profile fields, member code and check-in by code', async ({ page }) => {
    await onboard(page, 'empty')
    await page.goto('/members/new')
    await page.getByLabel('Full name').fill('Priya Code')
    await page.getByLabel(/^Phone/).fill('98200 00031')
    await page.getByLabel('Date of birth').fill('1990-05-20')
    await page.getByLabel('Gender').selectOption('female')
    await page.getByLabel('Emergency contact').fill('Rahul Code')
    await page.getByLabel('Emergency phone').fill('98200 00032')
    await page.getByLabel('Fitness goal').fill('Strength')
    await page.getByLabel('Health notes').fill('Asthma; keep inhaler nearby')
    await page.getByRole('button', { name: 'Add member' }).click()
    await expect(page).toHaveURL(/\/members\/mem_/)
    const main = page.getByRole('main')
    await expect(main).toContainText('GB-0001')
    await expect(main).toContainText('Rahul Code')
    await expect(main).toContainText('Asthma; keep inhaler nearby')
    await expect(main).toContainText('Strength')
    const stored = await readStore<{ memberCode: string; dateOfBirth: string; gender: string }>(page, 'members')
    expect(stored[0]).toMatchObject({ memberCode: 'GB-0001', dateOfBirth: '1990-05-20', gender: 'female' })

    await page.goto('/attendance')
    await page.getByRole('combobox').fill('GB-0001')
    await expect(page.getByRole('option', { name: /Priya Code/ })).toBeVisible()
  })

  test('PT sessions: book, conflict refused, complete; trainer and member pages show it', async ({ page }) => {
    await onboard(page, 'empty')
    await page.goto('/trainers')
    await page.getByRole('button', { name: 'Add trainer' }).first().click()
    const td = page.getByRole('dialog')
    await td.getByLabel('Full name').fill('Coach Kiran')
    await td.getByLabel(/^Phone/).fill('98200 00041')
    await td.getByLabel('Specialty').fill('Strength')
    await td.getByRole('button', { name: 'Add trainer' }).click()
    await expect(td).toBeHidden()
    const memberUrl = await addMember(page, 'Session Sam', '98200 00042')

    await page.goto('/sessions')
    await page.getByRole('button', { name: 'Book session' }).first().click()
    const dialog = page.getByRole('dialog')
    await dialog.getByRole('combobox', { name: /Search by name/ }).fill('Session')
    await page.getByRole('option', { name: /Session Sam/ }).click()
    const start = new Date(Date.now() + 2 * 86_400_000).toISOString().slice(0, 10) + 'T10:00'
    await dialog.getByLabel('Date and time').fill(start)
    await dialog.getByLabel('Duration (minutes)').fill('45')
    await expect(dialog).toContainText('No clashes')
    await dialog.getByRole('button', { name: 'Book session' }).click()
    await expect(dialog).toBeHidden()
    await expect(page.getByRole('status').filter({ hasText: 'Session booked' })).toBeVisible()
    expect((await readStore(page, 'sessions')).length).toBe(1)

    // Overlapping booking for the same member is refused.
    await page.getByRole('button', { name: 'Book session' }).first().click()
    const d2 = page.getByRole('dialog')
    await d2.getByRole('combobox', { name: /Search by name/ }).fill('Session')
    await page.getByRole('option', { name: /Session Sam/ }).click()
    await d2.getByLabel('Date and time').fill(start.replace('T10:00', 'T10:30'))
    await expect(d2).toContainText('Clashes with another session')
    await d2.getByRole('button', { name: 'Book session' }).click()
    await expect(d2.getByRole('alert')).toContainText('already has a session')
    await page.keyboard.press('Escape')
    await page.getByRole('dialog').getByRole('button', { name: 'Discard' }).click()
    expect((await readStore(page, 'sessions')).length).toBe(1)

    await page.getByRole('button', { name: 'Done' }).first().click()
    await expect(page.getByRole('status').filter({ hasText: 'Session completed' })).toBeVisible()
    await page.getByRole('tab', { name: /Past/ }).click()
    await expect(page.getByRole('main')).toContainText('Completed')

    await page.goto(memberUrl + '?tab=sessions')
    await expect(page.getByRole('main')).toContainText('Coach Kiran')
    await expect(page.getByRole('main')).toContainText('Completed')
  })

  test('equipment: add, report incident, resolve, retire; dashboard reflects alerts', async ({ page }) => {
    await onboard(page, 'empty')
    await page.goto('/equipment')
    await page.getByRole('button', { name: 'Add equipment' }).first().click()
    let dialog = page.getByRole('dialog')
    await dialog.getByLabel('Name').fill('Treadmill 1')
    await dialog.getByLabel('Category').fill('Cardio')
    await dialog.getByRole('button', { name: 'Add equipment' }).click()
    await expect(dialog).toBeHidden()
    await page.getByRole('button', { name: 'Report', exact: true }).click()
    dialog = page.getByRole('dialog')
    await dialog.getByLabel('What is wrong?').fill('Belt slipping')
    await dialog.getByLabel('Severity').selectOption('high')
    await dialog.getByLabel('Mark equipment as').selectOption('out_of_order')
    await dialog.getByRole('button', { name: 'Report incident' }).click()
    await expect(dialog).toBeHidden()
    await expect(page.getByRole('main')).toContainText('Out of order')
    await page.goto('/')
    await expect(page.getByRole('main')).toContainText('1 open incident, 1 high')
    await page.goto('/equipment')
    await page.getByRole('tab', { name: /Incidents/ }).click()
    await page.getByRole('button', { name: 'Start work' }).click()
    await page.getByRole('button', { name: 'Resolve' }).click()
    dialog = page.getByRole('dialog')
    await dialog.getByLabel('Resolution').fill('Belt replaced')
    await dialog.getByRole('button', { name: 'Mark resolved' }).click()
    await expect(dialog).toBeHidden()
    const incidents = await readStore<{ status: string; resolution: string }>(page, 'incidents')
    expect(incidents[0]).toMatchObject({ status: 'resolved', resolution: 'Belt replaced' })
    const equipment = await readStore<{ status: string }>(page, 'equipment')
    expect(equipment[0].status).toBe('ok')
    await page.getByRole('tab', { name: /Equipment/ }).click()
    await page.getByRole('button', { name: 'Retire' }).click()
    await expect(page.getByRole('status').filter({ hasText: 'Equipment retired' })).toBeVisible()
  })

  test('workout plans: use a template, assign to a member, print sheet shows member', async ({ page, context }) => {
    await onboard(page, 'empty')
    const memberUrl = await addMember(page, 'Plan Pat', '98200 00051')
    await page.goto('/workouts')
    await page.getByRole('button', { name: 'Use template' }).first().click()
    await expect(page.getByRole('status').filter({ hasText: 'Added' })).toBeVisible()
    expect((await readStore<{ source: string }>(page, 'workouts'))[0].source).toBe('library')
    await page.goto(memberUrl)
    const select = page.getByLabel('Assign workout plan')
    await select.selectOption({ index: 1 })
    await expect.poll(async () => (await readStore<{ workoutPlanId?: string }>(page, 'members'))[0].workoutPlanId).toBeTruthy()
    await expect(select.locator('option:checked')).toHaveText(/Beginner full body/)
    const [sheet] = await Promise.all([context.waitForEvent('page'), page.getByRole('button', { name: 'Print sheet' }).click()])
    await sheet.waitForLoadState()
    await expect(sheet.getByRole('article')).toContainText('Prepared for')
    await expect(sheet.getByRole('article')).toContainText('Plan Pat')
    await expect(sheet.getByRole('article')).toContainText('Beginner full body')
    await sheet.close()
  })

  test('activity page lists and filters events; new pages have no overflow at 390px', async ({ page }) => {
    await onboard(page, 'sample')
    await page.goto('/activity')
    await expect(page.getByRole('main')).toContainText('Loaded labelled sample data')
    await page.getByLabel('Kind').selectOption('system')
    await expect(page.getByRole('main')).toContainText('System')
    await page.setViewportSize({ width: 390, height: 844 })
    for (const route of ['/sessions', '/equipment', '/workouts', '/activity']) {
      await page.goto(route)
      await page.waitForLoadState('networkidle')
      const { scrollW, inner } = await page.evaluate(() => ({ scrollW: document.documentElement.scrollWidth, inner: window.innerWidth }))
      expect(scrollW, route).toBeLessThanOrEqual(inner)
    }
  })
})
